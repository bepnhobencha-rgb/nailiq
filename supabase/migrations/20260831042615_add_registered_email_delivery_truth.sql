-- Cross-purpose Resend delivery evidence for the unified NailIQ email registry.
--
-- This ledger is additive. Booking, owner-alert and OTP mail keep their stronger
-- domain-specific claims and reconciliation tables. The shared ledger provides
-- a PII-free answer for every registered email purpose without treating provider
-- acceptance as final delivery.

CREATE TABLE public.registered_email_delivery_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_event_id text NOT NULL UNIQUE,
  provider_message_id text NOT NULL,
  email_key text NOT NULL,
  audience text NOT NULL,
  event_type text NOT NULL,
  delivery_status text NOT NULL,
  recipient_fingerprint text NOT NULL,
  recipient_count integer NOT NULL,
  occurred_at timestamptz NOT NULL,
  payload_fingerprint text NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT registered_email_delivery_provider_event_check CHECK (
    provider_event_id ~ '^[!-~]{1,255}$'
  ),
  CONSTRAINT registered_email_delivery_provider_message_check CHECK (
    provider_message_id ~ '^[!-~]{1,255}$'
  ),
  CONSTRAINT registered_email_delivery_key_check CHECK (
    email_key ~ '^[a-z0-9_]{1,64}$'
  ),
  CONSTRAINT registered_email_delivery_audience_check CHECK (
    audience IN ('customer', 'owner', 'operator', 'security')
  ),
  CONSTRAINT registered_email_delivery_event_check CHECK (
    event_type IN (
      'email.sent', 'email.delivered', 'email.delivery_delayed',
      'email.failed', 'email.suppressed', 'email.bounced', 'email.complained'
    )
  ),
  CONSTRAINT registered_email_delivery_status_check CHECK (
    (event_type = 'email.sent' AND delivery_status = 'provider_accepted') OR
    (event_type = 'email.delivered' AND delivery_status = 'delivered') OR
    (event_type = 'email.delivery_delayed' AND delivery_status = 'delivery_delayed') OR
    (event_type = 'email.failed' AND delivery_status = 'failed') OR
    (event_type = 'email.suppressed' AND delivery_status = 'suppressed') OR
    (event_type = 'email.bounced' AND delivery_status = 'bounced') OR
    (event_type = 'email.complained' AND delivery_status = 'complained')
  ),
  CONSTRAINT registered_email_delivery_recipient_fingerprint_check CHECK (
    recipient_fingerprint ~ '^[0-9a-f]{64}$'
  ),
  CONSTRAINT registered_email_delivery_recipient_count_check CHECK (
    recipient_count BETWEEN 1 AND 100
  ),
  CONSTRAINT registered_email_delivery_payload_fingerprint_check CHECK (
    payload_fingerprint ~ '^[0-9a-f]{64}$'
  )
);

CREATE INDEX registered_email_delivery_message_timeline_idx
  ON public.registered_email_delivery_events (
    provider_message_id, recipient_fingerprint, occurred_at DESC, id DESC
  );

CREATE INDEX registered_email_delivery_operations_idx
  ON public.registered_email_delivery_events (
    email_key, audience, delivery_status, occurred_at DESC, id DESC
  );

ALTER TABLE public.registered_email_delivery_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.registered_email_delivery_events FORCE ROW LEVEL SECURITY;

REVOKE ALL PRIVILEGES ON TABLE public.registered_email_delivery_events
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE public.registered_email_delivery_events_id_seq
  FROM PUBLIC, anon, authenticated, service_role;

CREATE POLICY registered_email_delivery_events_deny_direct
  ON public.registered_email_delivery_events AS RESTRICTIVE
  FOR ALL TO PUBLIC
