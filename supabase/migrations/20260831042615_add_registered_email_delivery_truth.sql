  WITH CHECK (false);

CREATE OR REPLACE FUNCTION public.record_resend_registered_email_delivery_event(
  p_provider_event_id text,
  p_provider_message_id text,
  p_email_key text,
  p_audience text,
  p_event_type text,
  p_recipient_fingerprint text,
  p_recipient_count integer,
  p_occurred_at timestamptz,
  p_payload_fingerprint text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_delivery_status text;
  v_inserted_id bigint;
  v_existing public.registered_email_delivery_events%ROWTYPE;
BEGIN
  IF p_provider_event_id IS NULL
     OR p_provider_event_id !~ '^[!-~]{1,255}$'
     OR p_provider_message_id IS NULL
     OR p_provider_message_id !~ '^[!-~]{1,255}$'
     OR p_email_key IS NULL
     OR p_email_key !~ '^[a-z0-9_]{1,64}$'
     OR p_audience IS NULL
     OR p_audience NOT IN ('customer', 'owner', 'operator', 'security')
     OR p_event_type IS NULL
     OR p_event_type NOT IN (
       'email.sent', 'email.delivered', 'email.delivery_delayed',
       'email.failed', 'email.suppressed', 'email.bounced', 'email.complained'
     )
     OR p_recipient_fingerprint IS NULL
     OR p_recipient_fingerprint !~ '^[0-9a-f]{64}$'
     OR p_recipient_count IS NULL
     OR p_recipient_count NOT BETWEEN 1 AND 100
     OR p_occurred_at IS NULL
     OR p_occurred_at > now() + interval '10 minutes'
     OR p_payload_fingerprint IS NULL
     OR p_payload_fingerprint !~ '^[0-9a-f]{64}$'
  THEN
    RETURN jsonb_build_object('success', false, 'code', 'event_rejected');
  END IF;

  v_delivery_status := CASE p_event_type
    WHEN 'email.sent' THEN 'provider_accepted'
    WHEN 'email.delivered' THEN 'delivered'
    WHEN 'email.delivery_delayed' THEN 'delivery_delayed'
    WHEN 'email.failed' THEN 'failed'
    WHEN 'email.suppressed' THEN 'suppressed'
    WHEN 'email.bounced' THEN 'bounced'
    WHEN 'email.complained' THEN 'complained'
  END;

  INSERT INTO public.registered_email_delivery_events (
    provider_event_id,
    provider_message_id,
    email_key,
    audience,
    event_type,
    delivery_status,
    recipient_fingerprint,
    recipient_count,
    occurred_at,
    payload_fingerprint
  ) VALUES (
    p_provider_event_id,
    p_provider_message_id,
    p_email_key,
    p_audience,
    p_event_type,
    v_delivery_status,
    p_recipient_fingerprint,
    p_recipient_count,
    p_occurred_at,
    p_payload_fingerprint
  )
  ON CONFLICT (provider_event_id) DO NOTHING
  RETURNING id INTO v_inserted_id;

  IF v_inserted_id IS NOT NULL THEN
    RETURN jsonb_build_object(
      'success', true,
      'code', 'event_applied',
      'delivery_status', v_delivery_status
    );
  END IF;

  SELECT e.*
  INTO v_existing
  FROM public.registered_email_delivery_events AS e
  WHERE e.provider_event_id = p_provider_event_id;

  IF v_existing.provider_message_id = p_provider_message_id
     AND v_existing.email_key = p_email_key
     AND v_existing.audience = p_audience
     AND v_existing.event_type = p_event_type
     AND v_existing.recipient_fingerprint = p_recipient_fingerprint
     AND v_existing.recipient_count = p_recipient_count
     AND v_existing.occurred_at = p_occurred_at
     AND v_existing.payload_fingerprint = p_payload_fingerprint
  THEN
    RETURN jsonb_build_object(
      'success', true,
      'code', 'event_replay',
      'delivery_status', v_existing.delivery_status
    );
  END IF;

  RETURN jsonb_build_object('success', false, 'code', 'event_conflict');
END;
$$;

CREATE OR REPLACE FUNCTION public.load_registered_email_delivery_truth(
  p_email_key text DEFAULT NULL,
  p_audience text DEFAULT NULL,
  p_delivery_status text DEFAULT NULL,
  p_limit integer DEFAULT 100
)
RETURNS TABLE (
  provider_message_id text,
  email_key text,
  audience text,
  delivery_status text,
  event_type text,
  recipient_count integer,
  occurred_at timestamptz,
  received_at timestamptz
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT
    e.provider_message_id,
    e.email_key,
    e.audience,
    e.delivery_status,
    e.event_type,
    e.recipient_count,
    e.occurred_at,
    e.received_at
  FROM public.registered_email_delivery_events AS e
  WHERE (p_email_key IS NULL OR e.email_key = p_email_key)
    AND (p_audience IS NULL OR e.audience = p_audience)
    AND (p_delivery_status IS NULL OR e.delivery_status = p_delivery_status)
  ORDER BY e.occurred_at DESC, e.id DESC
  LIMIT LEAST(GREATEST(COALESCE(p_limit, 100), 1), 500)
$$;

