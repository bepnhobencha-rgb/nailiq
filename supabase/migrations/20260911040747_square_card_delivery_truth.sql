CREATE FUNCTION public.complete_booking_card_save_operation(p_operation_id uuid,p_attempt_token uuid,p_outcome text,p_provider_reference text,
 p_card_id text,p_customer_id text,p_card_brand text,p_card_last4 text,p_consent_at timestamptz,p_consent_meta jsonb,p_error_code text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE v_op public.booking_card_save_operations%ROWTYPE; v_result jsonb;
BEGIN
 IF p_attempt_token IS NULL OR p_outcome IS NULL THEN RETURN jsonb_build_object('ok',false,'code','invalid_completion'); END IF;
 SELECT * INTO v_op FROM public.booking_card_save_operations WHERE id=p_operation_id;
 IF p_outcome='succeeded' AND v_op.mode='save_card' AND (
   coalesce(p_customer_id,'') !~ '^[A-Za-z0-9:_-]{1,255}$'
   OR coalesce(p_card_brand,'') NOT IN ('VISA','MASTERCARD','AMERICAN_EXPRESS','AMEX','DISCOVER','DISCOVER_DINERS','DINERS','DINERS_CLUB','JCB','CHINA_UNIONPAY','UNIONPAY','UNION_PAY','INTERAC','EFTPOS','FELICA','OTHER_BRAND')
   OR p_card_id IS DISTINCT FROM p_provider_reference
   OR coalesce(p_consent_meta->>'policyVersion','') !~ '^nsp_[0-9a-f]{64}$'
   OR v_op.consent_at IS DISTINCT FROM p_consent_at OR v_op.consent_meta IS DISTINCT FROM p_consent_meta
   OR (v_op.provider='square' AND (v_op.expected_customer_id IS DISTINCT FROM p_customer_id
     OR v_op.card_dispatch_bound_at IS NULL))) THEN
   RETURN jsonb_build_object('ok',false,'code','invalid_completion'); END IF;
 v_result:=public.complete_booking_card_save_operation_pre_delivery_truth(p_operation_id,p_attempt_token,p_outcome,
   p_provider_reference,p_card_id,p_customer_id,p_card_brand,p_card_last4,p_consent_at,p_consent_meta,p_error_code);
 IF v_result->>'ok'='true' AND v_op.mode='save_card' THEN
   UPDATE public.booking_card_save_operations SET result_json=result_json||jsonb_build_object('customer_id',p_customer_id),
     next_reconcile_at=NULL,resolution_code='provider_card_found' WHERE id=p_operation_id;
 ELSIF v_result->>'code'='save_failed' THEN
   UPDATE public.booking_card_save_operations SET next_reconcile_at=NULL,resolution_code='customer_reentry_required'
     WHERE id=p_operation_id;
 END IF;
 RETURN v_result;
END; $$;

CREATE OR REPLACE FUNCTION public.reconcile_stale_booking_card_save_operations(p_limit integer)
RETURNS SETOF jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE v_op public.booking_card_save_operations%ROWTYPE; v_token uuid;
BEGIN
 -- Preparation/claim has a two minute dispatch deadline. A process that never
 -- prepared cannot dispatch later, so release that abandoned claim safely.
 FOR v_op IN SELECT * FROM public.booking_card_save_operations WHERE status='sending'
   AND dispatch_prepared_at IS NULL AND created_at<transaction_timestamp()-interval '3 minutes'
   ORDER BY created_at LIMIT least(greatest(coalesce(p_limit,0),0),25)
 LOOP
   PERFORM public.complete_booking_card_save_operation(v_op.id,v_op.attempt_token,'failed',NULL,NULL,NULL,NULL,NULL,
     NULL,NULL,'dispatch_prepare_uncertain');
 END LOOP;
 FOR v_op IN SELECT * FROM public.booking_card_save_operations WHERE status IN ('sending','unknown')
   AND dispatch_prepared_at IS NOT NULL AND next_reconcile_at<=transaction_timestamp()
   AND (reconciliation_lease_expires_at IS NULL OR reconciliation_lease_expires_at<=transaction_timestamp())
   ORDER BY next_reconcile_at,id LIMIT least(greatest(coalesce(p_limit,0),0),25) FOR UPDATE SKIP LOCKED
 LOOP
   v_token:=extensions.gen_random_uuid();
   UPDATE public.booking_card_save_operations SET reconciliation_token=v_token,
     reconciliation_lease_expires_at=transaction_timestamp()+interval '2 minutes' WHERE id=v_op.id;
   RETURN NEXT jsonb_build_object('operation_id',v_op.id,'attempt_token',v_token,'booking_id',v_op.booking_id,
     'salon_id',v_op.salon_id,'provider',v_op.provider,'provider_reference_key','nq-card:'||v_op.id::text,
     'expected_customer_id',v_op.expected_customer_id,'expected_merchant_id',v_op.expected_merchant_id,
     'expected_environment',v_op.expected_environment);
 END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION public.complete_booking_card_save_reconciliation(p_operation_id uuid,p_attempt_token uuid,p_outcome text,
 p_card_id text DEFAULT NULL,p_customer_id text DEFAULT NULL,p_card_brand text DEFAULT NULL,p_card_last4 text DEFAULT NULL)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE v_op public.booking_card_save_operations%ROWTYPE; v_booking public.bookings%ROWTYPE;
 v_now timestamptz:=transaction_timestamp(); v_result jsonb; v_outcome text:=p_outcome; v_empty integer;
 v_code text; v_terminal boolean; v_read boolean; v_consent_refresh boolean:=false;
BEGIN
 IF p_operation_id IS NULL OR p_attempt_token IS NULL OR p_outcome IS NULL OR p_outcome NOT IN
   ('found','not_found','multiple_matches','invalid_card','disabled_card','read_failed','config_unavailable','manual_review') THEN
   RETURN jsonb_build_object('ok',false,'code','invalid_completion'); END IF;
 SELECT b.* INTO v_booking FROM public.bookings b JOIN public.booking_card_save_operations op
   ON op.booking_id=b.id AND op.salon_id=b.salon_id WHERE op.id=p_operation_id;
 IF NOT FOUND THEN RETURN jsonb_build_object('ok',false,'code','operation_not_found'); END IF;
 -- Same lock order as claim/completion/retry, including group bookings.
 PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(CASE WHEN v_booking.group_id IS NULL
   THEN 'booking-management:'||v_booking.id::text ELSE 'booking-management-group:'||v_booking.group_id::text END,0));
 SELECT * INTO v_op FROM public.booking_card_save_operations WHERE id=p_operation_id FOR UPDATE;
 IF v_op.status='succeeded' THEN RETURN v_op.result_json||jsonb_build_object('idempotent',true); END IF;
 IF v_op.reconciliation_token IS DISTINCT FROM p_attempt_token
   OR v_op.reconciliation_lease_expires_at IS NULL OR v_op.reconciliation_lease_expires_at<=v_now
   OR v_op.status NOT IN ('sending','unknown') OR v_op.dispatch_prepared_at IS NULL THEN
   RETURN jsonb_build_object('ok',false,'code','claim_mismatch'); END IF;
 SELECT * INTO v_booking FROM public.bookings WHERE id=v_op.booking_id AND salon_id=v_op.salon_id FOR UPDATE;
 IF v_outcome IN ('found','disabled_card') AND (coalesce(p_card_id,'') !~ '^[A-Za-z0-9:_-]{1,255}$'
   OR coalesce(p_customer_id,'') !~ '^[A-Za-z0-9:_-]{1,255}$'
   OR coalesce(p_card_brand,'') NOT IN ('VISA','MASTERCARD','AMERICAN_EXPRESS','AMEX','DISCOVER','DISCOVER_DINERS','DINERS','DINERS_CLUB','JCB','CHINA_UNIONPAY','UNIONPAY','UNION_PAY','INTERAC','EFTPOS','FELICA','OTHER_BRAND') OR coalesce(p_card_last4,'') !~ '^[0-9]{4}$'
   OR (v_op.expected_customer_id IS NOT NULL AND v_op.expected_customer_id IS DISTINCT FROM p_customer_id)
   OR (v_booking.noshow_card_id IS NOT NULL AND v_booking.noshow_card_id IS DISTINCT FROM p_card_id)) THEN
   v_outcome:='invalid_card';
 END IF;
 IF v_outcome='disabled_card' AND (v_op.provider<>'square' OR v_op.mode<>'save_card'
   OR v_op.delivery_version IS DISTINCT FROM 2 OR v_op.expected_customer_id IS NULL
   OR v_op.expected_merchant_id IS NULL OR v_op.expected_environment IS NULL
   OR v_op.card_dispatch_bound_at IS NULL OR v_booking.noshow_card_id IS NOT NULL) THEN
   v_outcome:='invalid_card';
 END IF;
 IF v_outcome<>'found' THEN
   -- A later read invalidates any candidate offered for fresh consent. A
   -- multiple-match or failed read must never reuse an older single match.
   UPDATE public.booking_card_save_operations SET reconciliation_receipt=NULL,reconciliation_receipt_at=NULL WHERE id=v_op.id;
 END IF;
 IF v_outcome='found' THEN
   UPDATE public.booking_card_save_operations SET reconciliation_receipt=jsonb_build_object('card_id',p_card_id,
     'customer_id',p_customer_id,'brand',p_card_brand,'last4',p_card_last4),reconciliation_receipt_at=v_now WHERE id=v_op.id;
   IF coalesce(v_op.recovery_consent_at,v_op.consent_at) IS NULL OR
     coalesce(coalesce(v_op.recovery_consent_meta,v_op.consent_meta)->>'policyVersion','') !~ '^nsp_[0-9a-f]{64}$' THEN
     v_consent_refresh:=true; v_outcome:='manual_review';
   END IF;
 END IF;
 IF v_outcome='disabled_card' THEN
   UPDATE public.booking_card_save_operations SET reconciliation_receipt=jsonb_build_object('card_id',p_card_id,
     'customer_id',p_customer_id,'brand',p_card_brand,'last4',p_card_last4,'enabled',false),reconciliation_receipt_at=v_now WHERE id=v_op.id;
 END IF;
 v_read:=v_outcome IN ('found','not_found','multiple_matches','disabled_card');
 v_empty:=CASE WHEN v_outcome='not_found' THEN least(20,v_op.reconciliation_empty_count+1)
   WHEN v_outcome NOT IN ('read_failed','config_unavailable') THEN 0 ELSE v_op.reconciliation_empty_count END;
 -- Three complete successful reads AND a 15 minute observation window. A
 -- timeout/config failure neither proves absence nor advances this counter.
 v_terminal:=v_outcome='disabled_card' OR (v_outcome='not_found' AND v_empty>=3 AND v_now>=v_op.dispatch_prepared_at+interval '15 minutes');
 v_code:=CASE WHEN v_consent_refresh THEN 'consent_refresh_required' ELSE CASE v_outcome WHEN 'found' THEN 'provider_card_found' WHEN 'not_found' THEN 'reconciliation_not_found'
   WHEN 'disabled_card' THEN 'reconciliation_disabled_card'
   WHEN 'multiple_matches' THEN 'reconciliation_multiple_matches' WHEN 'invalid_card' THEN 'reconciliation_invalid_card'
   WHEN 'config_unavailable' THEN 'square_config_unavailable' WHEN 'read_failed' THEN 'reconciliation_read_failed'
   ELSE 'manual_review_required' END END;
 INSERT INTO public.booking_card_delivery_events(operation_id,booking_id,salon_id,provider,stage,code,retryability,reconciliation_outcome)
 VALUES(v_op.id,v_op.booking_id,v_op.salon_id,v_op.provider,'reconciliation',v_code,
   CASE WHEN v_outcome='found' THEN 'none' WHEN v_terminal THEN 'safe_retry'
     WHEN v_outcome IN ('multiple_matches','invalid_card','manual_review') THEN 'manual_review' ELSE 'reconcile_first' END,
   CASE WHEN v_terminal AND v_outcome='not_found' THEN 'retry_exhausted' ELSE v_outcome END);
 IF v_outcome='found' THEN
   v_result:=jsonb_build_object('ok',true,'code','reconciled_saved','outcome','succeeded','booking_id',v_op.booking_id,
     'salon_id',v_op.salon_id,'provider',v_op.provider,'mode',v_op.mode,'provider_reference',p_card_id,
     'customer_id',p_customer_id,'card_brand',p_card_brand,'card_last4',p_card_last4,'idempotent',false);
   UPDATE public.bookings SET noshow_card_id=p_card_id,noshow_customer_id=p_customer_id,noshow_card_brand=p_card_brand,
     noshow_card_last4=p_card_last4,noshow_consent_at=coalesce(v_op.recovery_consent_at,v_op.consent_at),
     noshow_consent_meta=coalesce(v_op.recovery_consent_meta,v_op.consent_meta),
     noshow_charge_status='saved' WHERE id=v_booking.id;
   UPDATE public.booking_card_save_operations SET status='succeeded',provider_reference=p_card_id,
     expected_customer_id=coalesce(expected_customer_id,p_customer_id),error_code=NULL,result_json=v_result,
     completion_fingerprint=encode(extensions.digest(convert_to(v_result::text,'UTF8'),'sha256'),'hex'),
     completed_at=coalesce(completed_at,v_now),updated_at=v_now,next_reconcile_at=NULL,resolution_code='provider_card_found',
     reconciliation_attempt_count=least(20,reconciliation_attempt_count+1),reconciliation_empty_count=0,
     reconciliation_token=NULL,reconciliation_lease_expires_at=NULL WHERE id=v_op.id;
 ELSE
   v_result:=jsonb_build_object('ok',false,'code',CASE WHEN v_terminal THEN 'retry_required'
     WHEN v_outcome IN ('multiple_matches','invalid_card','manual_review') THEN 'manual_review_required'
     ELSE 'reconciliation_pending' END,'booking_id',v_op.booking_id,'salon_id',v_op.salon_id,
     'outcome',CASE WHEN v_terminal THEN 'failed' ELSE 'unknown' END);
   UPDATE public.booking_card_save_operations SET status=CASE WHEN v_terminal THEN 'failed' ELSE 'unknown' END,
     error_code=coalesce(error_code,v_code),result_json=v_result,
     first_failure_stage=coalesce(first_failure_stage,'reconciliation'),first_failure_code=coalesce(first_failure_code,v_code),
     completion_fingerprint=coalesce(completion_fingerprint,encode(extensions.digest(convert_to(v_result::text,'UTF8'),'sha256'),'hex')),
     completed_at=coalesce(completed_at,v_now),updated_at=v_now,reconciliation_empty_count=v_empty,
     reconciliation_attempt_count=least(20,reconciliation_attempt_count+CASE WHEN v_read THEN 1 ELSE 0 END),
     resolution_code=CASE WHEN v_terminal THEN 'customer_reentry_required'
       WHEN v_outcome IN ('multiple_matches','invalid_card','manual_review') THEN 'manual_review_required'
       WHEN v_outcome='not_found' THEN 'provider_card_not_found' ELSE resolution_code END,
     next_reconcile_at=CASE WHEN v_terminal OR v_outcome IN ('multiple_matches','invalid_card','manual_review') THEN NULL
       ELSE v_now+interval '5 minutes' END,reconciliation_token=NULL,reconciliation_lease_expires_at=NULL WHERE id=v_op.id;
 END IF;
 -- Invalidate dispatch authority even if the original HTTP process died before
 -- consuming it. The old token can still read recovery status until expiry.
 UPDATE public.booking_management_capabilities SET revoked_at=coalesce(revoked_at,v_now),revoke_reason='card_delivery_settled'
   WHERE id=v_op.capability_id AND consumed_at IS NULL
     AND (revoked_at IS NULL OR revoke_reason='card_delivery_settled');
 RETURN jsonb_build_object('ok',true,'code',v_result->>'code');
END; $$;

CREATE FUNCTION public.booking_card_protection_state(p_booking public.bookings) RETURNS text
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path TO '' AS $$
DECLARE v_op public.booking_card_save_operations%ROWTYPE;
BEGIN
 SELECT * INTO v_op FROM public.booking_card_save_operations WHERE booking_id=p_booking.id
   AND salon_id=p_booking.salon_id AND mode='save_card' ORDER BY created_at DESC,delivery_sequence DESC,id DESC LIMIT 1;
 IF FOUND THEN
   IF v_op.status='succeeded' AND v_op.provider_reference IS NOT DISTINCT FROM p_booking.noshow_card_id
     AND coalesce(p_booking.noshow_card_id,'') ~ '^[A-Za-z0-9:_-]{1,255}$'
     AND coalesce(p_booking.noshow_customer_id,'') ~ '^[A-Za-z0-9:_-]{1,255}$'
     AND v_op.result_json->>'customer_id' IS NOT DISTINCT FROM p_booking.noshow_customer_id
     AND v_op.result_json->>'card_brand' IS NOT DISTINCT FROM p_booking.noshow_card_brand
     AND coalesce(p_booking.noshow_card_brand,'') IN ('VISA','MASTERCARD','AMERICAN_EXPRESS','AMEX','DISCOVER','DISCOVER_DINERS','DINERS','DINERS_CLUB','JCB','CHINA_UNIONPAY','UNIONPAY','UNION_PAY','INTERAC','EFTPOS','FELICA','OTHER_BRAND')
     AND v_op.result_json->>'card_last4' IS NOT DISTINCT FROM p_booking.noshow_card_last4
     AND coalesce(p_booking.noshow_card_last4,'') ~ '^[0-9]{4}$'
     AND p_booking.noshow_consent_at IS NOT NULL AND coalesce(v_op.recovery_consent_at,v_op.consent_at) IS NOT DISTINCT FROM p_booking.noshow_consent_at
     AND coalesce(v_op.recovery_consent_meta,v_op.consent_meta) IS NOT DISTINCT FROM p_booking.noshow_consent_meta
     AND coalesce(p_booking.noshow_consent_meta->>'policyVersion','') ~ '^nsp_[0-9a-f]{64}$'
     AND v_op.completion_fingerprint IS NOT NULL THEN RETURN 'saved'; END IF;
   IF v_op.status='unknown' THEN
     RETURN CASE WHEN v_op.resolution_code='manual_review_required' THEN 'manual_review' ELSE 'reconciliation_pending' END;
   ELSIF v_op.status='sending' THEN RETURN 'saving';
   ELSIF v_op.status='failed' THEN RETURN 'retry_required';
   ELSIF v_op.status='succeeded' AND p_booking.noshow_card_id IS NULL AND p_booking.noshow_customer_id IS NULL
     AND p_booking.noshow_charge_status='removed_by_customer' AND EXISTS(
       SELECT 1 FROM public.booking_card_management_operations removal
       WHERE removal.booking_id=p_booking.id AND removal.salon_id=p_booking.salon_id
         AND removal.operation='remove_card' AND removal.status='succeeded'
         AND removal.provider_reference=v_op.provider_reference
         AND removal.provider_material->>'card_id'=v_op.provider_reference
         AND removal.provider_material->>'customer_id'=v_op.result_json->>'customer_id'
         AND removal.result_json->>'code'='removed' AND removal.result_json->>'outcome'='succeeded'
         AND removal.completed_at>=v_op.completed_at AND removal.created_at>=v_op.completed_at
     ) THEN
     -- A durable removal receipt closes the previous card lifecycle. Missing
     -- IDs without this proof remain manual review, never a retry shortcut.
     RETURN 'retry_required';
   ELSE RETURN 'manual_review'; END IF;
 END IF;
 IF p_booking.noshow_card_id IS NOT NULL THEN RETURN 'manual_review'; END IF;
 RETURN CASE WHEN p_booking.noshow_card_required THEN 'awaiting_card' ELSE 'not_required' END;
END; $$;

