CREATE FUNCTION public.record_booking_card_delivery_failure(
 p_operation_id uuid,p_attempt_token uuid,p_stage text,p_code text,p_http_status integer,
 p_square_codes text[],p_square_categories text[],p_retryability text
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE v_op public.booking_card_save_operations%ROWTYPE;
BEGIN
 IF p_attempt_token IS NULL OR p_stage IS NULL OR p_stage NOT IN ('configuration','customer_search','customer_create',
   'card_create','receipt_validation','dispatch_preparation','database_completion','reconciliation')
 OR p_code IS NULL OR p_code NOT IN ('square_config_unavailable','square_customer_search_failed','square_customer_create_failed',
   'square_card_create_failed','square_invalid_card_receipt','provider_response_lost','dispatch_prepare_uncertain',
   'dispatch_binding_uncertain','database_completion_uncertain','consent_policy_unavailable',
   'reconciliation_read_failed','reconciliation_read_incomplete','reconciliation_invalid_card')
 OR p_retryability IS NULL OR p_retryability NOT IN ('safe_retry','new_card','reconcile_first','manual_review')
 OR (p_http_status IS NOT NULL AND p_http_status NOT BETWEEN 100 AND 599)
 OR NOT coalesce(p_square_codes,'{}') <@ ARRAY['UNAUTHORIZED','ACCESS_TOKEN_EXPIRED','ACCESS_TOKEN_REVOKED','FORBIDDEN',
   'INSUFFICIENT_SCOPES','RATE_LIMITED','INTERNAL_SERVER_ERROR','SERVICE_UNAVAILABLE','BAD_REQUEST','INVALID_REQUEST_ERROR',
   'INVALID_VALUE','MISSING_REQUIRED_PARAMETER','INVALID_PHONE_NUMBER','INVALID_EMAIL_ADDRESS','NOT_FOUND','CONFLICT',
   'IDEMPOTENCY_KEY_REUSED','CARD_DECLINED','GENERIC_DECLINE','CARD_NOT_SUPPORTED','CARD_EXPIRED','INVALID_CARD_DATA',
   'VERIFY_CVV_FAILURE','VERIFY_AVS_FAILURE','CARD_DECLINED_VERIFICATION_REQUIRED','SOURCE_EXPIRED','SOURCE_USED',
   'CUSTOMER_NOT_FOUND','CARD_TOKEN_EXPIRED','CARD_TOKEN_USED']::text[]
 OR NOT coalesce(p_square_categories,'{}') <@ ARRAY['API_ERROR','AUTHENTICATION_ERROR','INVALID_REQUEST_ERROR',
   'RATE_LIMIT_ERROR','PAYMENT_METHOD_ERROR','REFUND_ERROR']::text[]
 THEN RETURN jsonb_build_object('ok',false,'code','invalid_diagnostic'); END IF;
 SELECT * INTO v_op FROM public.booking_card_save_operations WHERE id=p_operation_id FOR UPDATE;
 IF NOT FOUND OR (v_op.attempt_token IS DISTINCT FROM p_attempt_token AND
   v_op.reconciliation_token IS DISTINCT FROM p_attempt_token) THEN
   RETURN jsonb_build_object('ok',false,'code','claim_mismatch'); END IF;
 INSERT INTO public.booking_card_delivery_events(operation_id,booking_id,salon_id,provider,stage,code,
   provider_http_status,square_codes,square_categories,retryability)
 VALUES(v_op.id,v_op.booking_id,v_op.salon_id,v_op.provider,p_stage,p_code,p_http_status,
   coalesce(p_square_codes,'{}'),coalesce(p_square_categories,'{}'),p_retryability);
 UPDATE public.booking_card_save_operations SET first_failure_stage=coalesce(first_failure_stage,p_stage),
   first_failure_code=coalesce(first_failure_code,p_code) WHERE id=v_op.id;
 RETURN jsonb_build_object('ok',true);
END; $$;

CREATE FUNCTION public.bind_booking_card_save_dispatch(p_operation_id uuid,p_attempt_token uuid,
 p_customer_id text,p_merchant_id text,p_environment text) RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO '' AS $$
DECLARE v_op public.booking_card_save_operations%ROWTYPE;
BEGIN
 IF p_attempt_token IS NULL OR coalesce(p_customer_id,'') !~ '^[A-Za-z0-9:_-]{1,255}$'
 OR coalesce(p_merchant_id,'') !~ '^[A-Za-z0-9:_-]{1,255}$'
 OR p_environment IS NULL OR p_environment NOT IN ('sandbox','production') THEN
 RETURN jsonb_build_object('ok',false,'code','invalid_binding'); END IF;
 SELECT * INTO v_op FROM public.booking_card_save_operations WHERE id=p_operation_id FOR UPDATE;
 IF NOT FOUND OR v_op.attempt_token IS DISTINCT FROM p_attempt_token OR v_op.status<>'sending'
 OR v_op.dispatch_prepared_at IS NULL OR v_op.created_at < transaction_timestamp()-interval '2 minutes'
 OR (v_op.expected_customer_id IS NOT NULL AND v_op.expected_customer_id IS DISTINCT FROM p_customer_id)
 OR (v_op.expected_merchant_id IS NOT NULL AND v_op.expected_merchant_id IS DISTINCT FROM p_merchant_id)
 OR (v_op.expected_environment IS NOT NULL AND v_op.expected_environment IS DISTINCT FROM p_environment)
 THEN RETURN jsonb_build_object('ok',false,'code','claim_mismatch'); END IF;
 UPDATE public.booking_card_save_operations SET expected_customer_id=p_customer_id,
   expected_merchant_id=p_merchant_id,expected_environment=p_environment,
   card_dispatch_bound_at=coalesce(card_dispatch_bound_at,transaction_timestamp()) WHERE id=v_op.id;
 RETURN jsonb_build_object('ok',true);
END; $$;

